"""hrsg1_ip component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    model.add(
        Splitter(
            "ip1_pump_split",
            s["hrsg1.ip_pump_in"],
            s["hrsg1.ip_pump1_in"],
            s["hrsg1.ip_pump2_in"],
            system_name,
        )
    )
    model.add(
        Pump(
            "ip1_pump1",
            s["hrsg1.ip_pump1_in"],
            s["hrsg1.ip_pump1_out"],
            system_name,
            row.get("ip1_pump1.power"),
        )
    )
    model.add(
        Pump(
            "ip1_pump2",
            s["hrsg1.ip_pump2_in"],
            s["hrsg1.ip_pump2_out"],
            system_name,
            row.get("ip1_pump2.power"),
        )
    )
    model.add(
        Mixer(
            "ip1_pump_merge",
            s["hrsg1.ip_pump1_out"],
            s["hrsg1.ip_pump2_out"],
            s["hrsg1.ip_pump_out"],
            system_name,
        )
    )
    feed = Splitter(
        "ip1_feed_split",
        s["hrsg1.ip_pump_out"],
        s["hrsg1.ip_feed"],
        s["hrsg1.rh_spray"],
        system_name,
    )
    feed.add_outlet(s["hrsg1.ip_pump_return"])
    model.add(feed)
    model.add(
        HeatExchanger(
            "ip1_economizer",
            s["hrsg1.ip_feed"],
            s["hrsg1.ip_economizer_out"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "ip1_feed_valve",
            s["hrsg1.ip_economizer_out"],
            s["hrsg1.ip_to_drum"],
            system_name,
        )
    )
    drum = HeatExchanger(
        "ip1_drum_evaporator",
        s["hrsg1.ip_to_drum"],
        s["hrsg1.ip_drum_steam"],
        system_name,
    )
    drum.add_outlet(s["hrsg1.ip_drum_drain"])
    model.add(drum)
    model.add(
        HeatExchanger(
            "ip1_superheater",
            s["hrsg1.ip_drum_steam"],
            s["hrsg1.ip_fresh"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip1_cold_reheat_bypass_mix",
            s["hrsg1.cold_reheat"],
            s["hrsg1.hp_bypass_out"],
            s["hrsg1.cold_reheat_with_bypass"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip1_fresh_steam_mix",
            s["hrsg1.cold_reheat_with_bypass"],
            s["hrsg1.ip_fresh"],
            s["hrsg1.reheat_mixed"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "ip1_reheater1", s["hrsg1.reheat_mixed"], s["hrsg1.rh1_out"], system_name
        )
    )
    model.add(
        Mixer(
            "ip1_attemperator",
            s["hrsg1.rh1_out"],
            s["hrsg1.rh_spray"],
            s["hrsg1.rh_after_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "ip1_reheater2", s["hrsg1.rh_after_spray"], s["hrsg1.rh2_out"], system_name
        )
    )
    model.add(
        HeatExchanger(
            "ip1_reheater3", s["hrsg1.rh2_out"], s["hrsg1.hot_reheat"], system_name
        )
    )
    model.add(
        Splitter(
            "ip1_main_split",
            s["hrsg1.hot_reheat"],
            s["hrsg1.rh_to_st"],
            s["hrsg1.ip_bypass_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "ip1_bypass_valve",
            s["hrsg1.ip_bypass_in"],
            s["hrsg1.ip_bypass_throttled"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip1_bypass_spray",
            s["hrsg1.ip_bypass_throttled"],
            s["hrsg1.ip_bypass_spray"],
            s["hrsg1.ip_bypass_out"],
            system_name,
        )
    )
    model.add(
        Splitter(
            "ip1_bypass_destination",
            s["hrsg1.ip_bypass_out"],
            s["hrsg1.ip_bypass_to_heat"],
            s["hrsg1.ip_bypass_to_condenser"],
            system_name,
        )
    )
    return model
