"""hrsg2_ip component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    model.add(
        Splitter(
            "ip2_pump_split",
            s["hrsg2.ip_pump_in"],
            s["hrsg2.ip_pump1_in"],
            s["hrsg2.ip_pump2_in"],
            system_name,
        )
    )
    model.add(
        Pump(
            "ip2_pump1",
            s["hrsg2.ip_pump1_in"],
            s["hrsg2.ip_pump1_out"],
            system_name,
            row.get("ip2_pump1.power"),
        )
    )
    model.add(
        Pump(
            "ip2_pump2",
            s["hrsg2.ip_pump2_in"],
            s["hrsg2.ip_pump2_out"],
            system_name,
            row.get("ip2_pump2.power"),
        )
    )
    model.add(
        Mixer(
            "ip2_pump_merge",
            s["hrsg2.ip_pump1_out"],
            s["hrsg2.ip_pump2_out"],
            s["hrsg2.ip_pump_out"],
            system_name,
        )
    )
    feed = Splitter(
        "ip2_feed_split",
        s["hrsg2.ip_pump_out"],
        s["hrsg2.ip_feed"],
        s["hrsg2.rh_spray"],
        system_name,
    )
    feed.add_outlet(s["hrsg2.ip_pump_return"])
    model.add(feed)
    model.add(
        HeatExchanger(
            "ip2_economizer",
            s["hrsg2.ip_feed"],
            s["hrsg2.ip_economizer_out"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "ip2_feed_valve",
            s["hrsg2.ip_economizer_out"],
            s["hrsg2.ip_to_drum"],
            system_name,
        )
    )
    drum = HeatExchanger(
        "ip2_drum_evaporator",
        s["hrsg2.ip_to_drum"],
        s["hrsg2.ip_drum_steam"],
        system_name,
    )
    drum.add_outlet(s["hrsg2.ip_drum_drain"])
    model.add(drum)
    model.add(
        HeatExchanger(
            "ip2_superheater",
            s["hrsg2.ip_drum_steam"],
            s["hrsg2.ip_fresh"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip2_cold_reheat_bypass_mix",
            s["hrsg2.cold_reheat"],
            s["hrsg2.hp_bypass_out"],
            s["hrsg2.cold_reheat_with_bypass"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip2_fresh_steam_mix",
            s["hrsg2.cold_reheat_with_bypass"],
            s["hrsg2.ip_fresh"],
            s["hrsg2.reheat_mixed"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "ip2_reheater1", s["hrsg2.reheat_mixed"], s["hrsg2.rh1_out"], system_name
        )
    )
    model.add(
        Mixer(
            "ip2_attemperator",
            s["hrsg2.rh1_out"],
            s["hrsg2.rh_spray"],
            s["hrsg2.rh_after_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "ip2_reheater2", s["hrsg2.rh_after_spray"], s["hrsg2.rh2_out"], system_name
        )
    )
    model.add(
        HeatExchanger(
            "ip2_reheater3", s["hrsg2.rh2_out"], s["hrsg2.hot_reheat"], system_name
        )
    )
    model.add(
        Splitter(
            "ip2_main_split",
            s["hrsg2.hot_reheat"],
            s["hrsg2.rh_to_st"],
            s["hrsg2.ip_bypass_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "ip2_bypass_valve",
            s["hrsg2.ip_bypass_in"],
            s["hrsg2.ip_bypass_throttled"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "ip2_bypass_spray",
            s["hrsg2.ip_bypass_throttled"],
            s["hrsg2.ip_bypass_spray"],
            s["hrsg2.ip_bypass_out"],
            system_name,
        )
    )
    model.add(
        Splitter(
            "ip2_bypass_destination",
            s["hrsg2.ip_bypass_out"],
            s["hrsg2.ip_bypass_to_heat"],
            s["hrsg2.ip_bypass_to_condenser"],
            system_name,
        )
    )
    return model
