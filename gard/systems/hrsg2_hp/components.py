"""hrsg2_hp component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    model.add(
        Splitter(
            "hp2_pump_split",
            s["hrsg2.hp_pump_in"],
            s["hrsg2.hp_pump1_in"],
            s["hrsg2.hp_pump2_in"],
            system_name,
        )
    )
    model.add(
        Pump(
            "hp2_pump1",
            s["hrsg2.hp_pump1_in"],
            s["hrsg2.hp_pump1_out"],
            system_name,
            row.get("hp2_pump1.power"),
        )
    )
    model.add(
        Pump(
            "hp2_pump2",
            s["hrsg2.hp_pump2_in"],
            s["hrsg2.hp_pump2_out"],
            system_name,
            row.get("hp2_pump2.power"),
        )
    )
    model.add(
        Mixer(
            "hp2_pump_merge",
            s["hrsg2.hp_pump1_out"],
            s["hrsg2.hp_pump2_out"],
            s["hrsg2.hp_pump_out"],
            system_name,
        )
    )
    feed = Splitter(
        "hp2_feed_split",
        s["hrsg2.hp_pump_out"],
        s["hrsg2.hp_feed"],
        s["hrsg2.hp_spray"],
        system_name,
    )
    feed.add_outlet(s["hrsg2.hp_bypass_spray"])
    feed.add_outlet(s["hrsg2.hp_pump_return"])
    model.add(feed)
    model.add(
        HeatExchanger(
            "hp2_economizer1",
            s["hrsg2.hp_economizer_in"],
            s["hrsg2.hp_economizer1_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp2_economizer2",
            s["hrsg2.hp_economizer1_out"],
            s["hrsg2.hp_economizer2_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp2_economizer3",
            s["hrsg2.hp_economizer2_out"],
            s["hrsg2.hp_to_drum"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "hp2_feed_valve",
            s["hrsg2.hp_feed"],
            s["hrsg2.hp_economizer_in"],
            system_name,
        )
    )
    drum = HeatExchanger(
        "hp2_drum_evaporator",
        s["hrsg2.hp_to_drum"],
        s["hrsg2.hp_drum_steam"],
        system_name,
    )
    drum.add_outlet(s["hrsg2.hp_drum_drain"])
    model.add(drum)
    model.add(
        HeatExchanger(
            "hp2_superheater1",
            s["hrsg2.hp_drum_steam"],
            s["hrsg2.hp_sh1_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp2_superheater2",
            s["hrsg2.hp_sh1_out"],
            s["hrsg2.hp_sh2_out"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "hp2_attemperator",
            s["hrsg2.hp_before_spray"],
            s["hrsg2.hp_spray"],
            s["hrsg2.hp_after_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp2_superheater3",
            s["hrsg2.hp_sh2_out"],
            s["hrsg2.hp_before_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp2_superheater4",
            s["hrsg2.hp_after_spray"],
            s["hrsg2.hp_main"],
            system_name,
        )
    )
    model.add(
        Splitter(
            "hp2_main_split",
            s["hrsg2.hp_main"],
            s["hrsg2.hp_to_st"],
            s["hrsg2.hp_bypass_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "hp2_bypass_valve",
            s["hrsg2.hp_bypass_in"],
            s["hrsg2.hp_bypass_throttled"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "hp2_bypass_spray",
            s["hrsg2.hp_bypass_throttled"],
            s["hrsg2.hp_bypass_spray"],
            s["hrsg2.hp_bypass_out"],
            system_name,
        )
    )
    return model
