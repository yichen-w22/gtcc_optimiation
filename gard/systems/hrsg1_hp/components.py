"""hrsg1_hp component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    model.add(
        Splitter(
            "hp1_pump_split",
            s["hrsg1.hp_pump_in"],
            s["hrsg1.hp_pump1_in"],
            s["hrsg1.hp_pump2_in"],
            system_name,
        )
    )
    model.add(
        Pump(
            "hp1_pump1",
            s["hrsg1.hp_pump1_in"],
            s["hrsg1.hp_pump1_out"],
            system_name,
            row.get("hp1_pump1.power"),
        )
    )
    model.add(
        Pump(
            "hp1_pump2",
            s["hrsg1.hp_pump2_in"],
            s["hrsg1.hp_pump2_out"],
            system_name,
            row.get("hp1_pump2.power"),
        )
    )
    model.add(
        Mixer(
            "hp1_pump_merge",
            s["hrsg1.hp_pump1_out"],
            s["hrsg1.hp_pump2_out"],
            s["hrsg1.hp_pump_out"],
            system_name,
        )
    )
    feed = Splitter(
        "hp1_feed_split",
        s["hrsg1.hp_pump_out"],
        s["hrsg1.hp_feed"],
        s["hrsg1.hp_spray"],
        system_name,
    )
    feed.add_outlet(s["hrsg1.hp_bypass_spray"])
    feed.add_outlet(s["hrsg1.hp_pump_return"])
    model.add(feed)
    model.add(
        HeatExchanger(
            "hp1_economizer1",
            s["hrsg1.hp_economizer_in"],
            s["hrsg1.hp_economizer1_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp1_economizer2",
            s["hrsg1.hp_economizer1_out"],
            s["hrsg1.hp_economizer2_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp1_economizer3",
            s["hrsg1.hp_economizer2_out"],
            s["hrsg1.hp_to_drum"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "hp1_feed_valve",
            s["hrsg1.hp_feed"],
            s["hrsg1.hp_economizer_in"],
            system_name,
        )
    )
    drum = HeatExchanger(
        "hp1_drum_evaporator",
        s["hrsg1.hp_to_drum"],
        s["hrsg1.hp_drum_steam"],
        system_name,
    )
    drum.add_outlet(s["hrsg1.hp_drum_drain"])
    model.add(drum)
    model.add(
        HeatExchanger(
            "hp1_superheater1",
            s["hrsg1.hp_drum_steam"],
            s["hrsg1.hp_sh1_out"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp1_superheater2",
            s["hrsg1.hp_sh1_out"],
            s["hrsg1.hp_sh2_out"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "hp1_attemperator",
            s["hrsg1.hp_before_spray"],
            s["hrsg1.hp_spray"],
            s["hrsg1.hp_after_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp1_superheater3",
            s["hrsg1.hp_sh2_out"],
            s["hrsg1.hp_before_spray"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "hp1_superheater4",
            s["hrsg1.hp_after_spray"],
            s["hrsg1.hp_main"],
            system_name,
        )
    )
    model.add(
        Splitter(
            "hp1_main_split",
            s["hrsg1.hp_main"],
            s["hrsg1.hp_to_st"],
            s["hrsg1.hp_bypass_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "hp1_bypass_valve",
            s["hrsg1.hp_bypass_in"],
            s["hrsg1.hp_bypass_throttled"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "hp1_bypass_spray",
            s["hrsg1.hp_bypass_throttled"],
            s["hrsg1.hp_bypass_spray"],
            s["hrsg1.hp_bypass_out"],
            system_name,
        )
    )
    return model
