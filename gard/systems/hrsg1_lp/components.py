"""hrsg1_lp component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    model.add(
        Mixer(
            "lp1_heat_recovery_return",
            s["hrsg1.lp_feed"],
            s["hrsg1.lp_from_heat_recovery"],
            s["hrsg1.lp_feed_after_recovery"],
            system_name,
        )
    )
    model.add(
        Splitter(
            "lp1_feed_split",
            s["hrsg1.lp_feed_after_recovery"],
            s["hrsg1.lp_feed_to_mix"],
            s["hrsg1.lp_economizer_bypass"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "lp1_recycle_mix",
            s["hrsg1.lp_feed_to_mix"],
            s["hrsg1.lp_recirc_out"],
            s["hrsg1.lp_economizer_in"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "lp1_economizer",
            s["hrsg1.lp_economizer_in"],
            s["hrsg1.lp_economizer_out"],
            system_name,
        )
    )
    split = Splitter(
        "lp1_recycle_split",
        s["hrsg1.lp_economizer_out"],
        s["hrsg1.lp_feed_mixed"],
        s["hrsg1.lp_recirc_in"],
        system_name,
    )
    split.add_outlet(s["hrsg1.lp_to_heat_recovery"])
    model.add(split)
    model.add(
        Splitter(
            "lp1_pump_split",
            s["hrsg1.lp_recirc_in"],
            s["hrsg1.lp_recirc_pump1_in"],
            s["hrsg1.lp_recirc_pump2_in"],
            system_name,
        )
    )
    model.add(
        Pump(
            "lp1_pump1",
            s["hrsg1.lp_recirc_pump1_in"],
            s["hrsg1.lp_recirc_pump1_out"],
            system_name,
            row.get("lp1_pump1.power"),
        )
    )
    model.add(
        Pump(
            "lp1_pump2",
            s["hrsg1.lp_recirc_pump2_in"],
            s["hrsg1.lp_recirc_pump2_out"],
            system_name,
            row.get("lp1_pump2.power"),
        )
    )
    model.add(
        Mixer(
            "lp1_pump_merge",
            s["hrsg1.lp_recirc_pump1_out"],
            s["hrsg1.lp_recirc_pump2_out"],
            s["hrsg1.lp_recirc_out"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "lp1_bypass_mix",
            s["hrsg1.lp_feed_mixed"],
            s["hrsg1.lp_economizer_bypass"],
            s["hrsg1.lp_drum_valve_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "lp1_drum_feed_valve",
            s["hrsg1.lp_drum_valve_in"],
            s["hrsg1.lp_to_drum"],
            system_name,
        )
    )
    drum = HeatExchanger(
        "lp1_drum_evaporator",
        s["hrsg1.lp_to_drum"],
        s["hrsg1.lp_saturated_steam"],
        system_name,
    )
    drum.add_outlet(s["hrsg1.lp_water"])
    drum.add_outlet(s["hrsg1.lp_drum_drain"])
    drum.add_inlet(s["hrsg1.hp_pump_return"])
    model.add(drum)
    model.add(
        Splitter(
            "lp1_water_split",
            s["hrsg1.lp_water"],
            s["hrsg1.hp_pump_in"],
            s["hrsg1.ip_pump_in"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "lp1_superheater",
            s["hrsg1.lp_saturated_steam"],
            s["hrsg1.lp_main"],
            system_name,
        )
    )
    main = Splitter(
        "lp1_main_split",
        s["hrsg1.lp_main"],
        s["hrsg1.lp_to_st"],
        s["hrsg1.lp_to_heat"],
        system_name,
    )
    main.add_outlet(s["hrsg1.lp_bypass_in"])
    model.add(main)
    model.add(
        ThrottleValve(
            "lp1_bypass_valve",
            s["hrsg1.lp_bypass_in"],
            s["hrsg1.lp_bypass_throttled"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "lp1_bypass_spray",
            s["hrsg1.lp_bypass_throttled"],
            s["hrsg1.lp_bypass_spray"],
            s["hrsg1.lp_bypass_out"],
            system_name,
        )
    )
    return model
