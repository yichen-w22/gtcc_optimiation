"""condenser component topology."""
from src.base.system import ComponentBook
from src.ST_model.accounting import EnergyConverter, Pump, Turbine, Mixer, Splitter, ThrottleValve, HeatExchanger


def build_components(row, streams, system_name):
    s = streams
    model = ComponentBook(system_name, row)
    condenser = HeatExchanger(
        "condenser",
        s["cooling.supply"],
        s["cooling.return"],
        system_name,
        s["st.lp_out"],
        s["cond.hotwell"],
    )
    condenser.add_inlet(s["hrsg1.ip_bypass_to_condenser"])
    condenser.add_inlet(s["hrsg2.ip_bypass_to_condenser"])
    condenser.add_inlet(s["hrsg1.lp_bypass_out"])
    condenser.add_inlet(s["hrsg2.lp_bypass_out"])
    condenser.add_inlet(s["cond.pre_recycle"])
    condenser.add_inlet(s["cond.main_recycle"])
    condenser.add_inlet(s["cond.overflow"])
    condenser.add_inlet(s["cond.makeup"])
    condenser.add_inlet(s["cond.drains"])
    condenser.add_outlet(s["cond.vacuum_extraction"])
    model.add(condenser)
    model.add(
        EnergyConverter(
            "vacuum_pump1",
            "unresolved_vacuum_pump",
            system_name,
            work=row.get("vacuum_pump1.work"),
            heat=None,
            heat_exergy=None,
            note="1号真空泵；缺入口气体流量、组成和出口状态；功输出为负表示耗电",
        )
    )
    model.add(
        EnergyConverter(
            "vacuum_pump2",
            "unresolved_vacuum_pump",
            system_name,
            work=row.get("vacuum_pump2.work"),
            heat=None,
            heat_exergy=None,
            note="2号真空泵；缺入口气体流量、组成和出口状态；功输出为负表示耗电",
        )
    )
    model.add(
        EnergyConverter(
            "vacuum_pump3",
            "unresolved_vacuum_pump",
            system_name,
            work=row.get("vacuum_pump3.work"),
            heat=None,
            heat_exergy=None,
            note="3号真空泵；缺入口气体流量、组成和出口状态；功输出为负表示耗电",
        )
    )
    model.add(
        ThrottleValve(
            "hotwell_outlet_pipe",
            s["cond.hotwell"],
            s["cond.pre_header_in"],
            system_name,
        )
    )
    split = Splitter(
        "pre_pump_split",
        s["cond.pre_header_in"],
        s["cond.pre_pump1_in"],
        s["cond.pre_pump2_in"],
        system_name,
    )
    split.add_outlet(s["cond.pre_pump3_in"])
    model.add(split)
    model.add(
        Pump(
            "pre_pump1",
            s["cond.pre_pump1_in"],
            s["cond.pre_pump1_out"],
            system_name,
            row.get("pre_pump1.power"),
        )
    )
    model.add(
        Pump(
            "pre_pump2",
            s["cond.pre_pump2_in"],
            s["cond.pre_pump2_out"],
            system_name,
            row.get("pre_pump2.power"),
        )
    )
    model.add(
        Pump(
            "pre_pump3",
            s["cond.pre_pump3_in"],
            s["cond.pre_pump3_out"],
            system_name,
            row.get("pre_pump3.power"),
        )
    )
    merge = Mixer(
        "pre_pump_merge",
        s["cond.pre_pump1_out"],
        s["cond.pre_pump2_out"],
        s["cond.pre_header_out"],
        system_name,
    )
    merge.add_inlet(s["cond.pre_pump3_out"])
    model.add(merge)
    split = Splitter(
        "pre_recycle_split",
        s["cond.pre_header_out"],
        s["cond.pre_forward"],
        s["cond.pre_recycle"],
        system_name,
    )
    split.add_outlet(s["cond.overflow"])
    model.add(split)
    model.add(
        Splitter(
            "cond_control_split",
            s["cond.pre_forward"],
            s["cond.control_in"],
            s["cond.control_bypass_in"],
            system_name,
        )
    )
    model.add(
        ThrottleValve(
            "cond_control", s["cond.control_in"], s["cond.control_out"], system_name
        )
    )
    model.add(
        ThrottleValve(
            "cond_control_bypass",
            s["cond.control_bypass_in"],
            s["cond.control_bypass_out"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "cond_control_merge",
            s["cond.control_out"],
            s["cond.control_bypass_out"],
            s["cond.before_drain_mix"],
            system_name,
        )
    )
    model.add(
        Mixer(
            "heating_drain_mix",
            s["cond.before_drain_mix"],
            s["heat.drain_return"],
            s["cond.gland_heater_in"],
            system_name,
        )
    )
    model.add(
        HeatExchanger(
            "gland_heater",
            s["cond.gland_heater_in"],
            s["cond.gland_heater_out"],
            system_name,
            s["aux.gland_exhaust"],
            s["aux.gland_drain"],
        )
    )
    split = Splitter(
        "cond_pump_split",
        s["cond.gland_heater_out"],
        s["cond.pump1_in"],
        s["cond.pump2_in"],
        system_name,
    )
    split.add_outlet(s["cond.pump3_in"])
    model.add(split)
    model.add(
        Pump(
            "cond_pump1",
            s["cond.pump1_in"],
            s["cond.pump1_out"],
            system_name,
            row.get("cond_pump1.power"),
        )
    )
    model.add(
        Pump(
            "cond_pump2",
            s["cond.pump2_in"],
            s["cond.pump2_out"],
            system_name,
            row.get("cond_pump2.power"),
        )
    )
    model.add(
        Pump(
            "cond_pump3",
            s["cond.pump3_in"],
            s["cond.pump3_out"],
            system_name,
            row.get("cond_pump3.power"),
        )
    )
    merge = Mixer(
        "cond_pump_merge",
        s["cond.pump1_out"],
        s["cond.pump2_out"],
        s["cond.pump_header_out"],
        system_name,
    )
    merge.add_inlet(s["cond.pump3_out"])
    model.add(merge)
    split = Splitter(
        "cond_users_split",
        s["cond.pump_header_out"],
        s["cond.filter_in"],
        s["cond.main_recycle"],
        system_name,
    )
    split.add_outlet(s["hrsg1.ip_bypass_spray"])
    split.add_outlet(s["hrsg2.ip_bypass_spray"])
    split.add_outlet(s["hrsg1.lp_bypass_spray"])
    split.add_outlet(s["hrsg2.lp_bypass_spray"])
    split.add_outlet(s["cond.other_users"])
    model.add(split)
    model.add(
        ThrottleValve(
            "iron_filter", s["cond.filter_in"], s["cond.to_boilers"], system_name
        )
    )
    model.add(
        Splitter(
            "boiler_feed_split",
            s["cond.to_boilers"],
            s["hrsg1.lp_feed"],
            s["hrsg2.lp_feed"],
            system_name,
        )
    )
    return model
